const BY_SUITE = new Map<SuiteId, CollectionId>(
  COLLECTION_IDS.flatMap((id) => COLLECTIONS[id].suites.map((suite) => [suite, id] as const)),
);

/** The collection a theme belongs to. */
export function collectionOf(suite: SuiteId): CollectionId {
  const id = BY_SUITE.get(suite);
  if (!id) throw new Error(`Theme ${suite} has no collection (src/lib/gallery/collections.ts)`);
  return id;
}

/** Where a theme sits in its collection, so a collection lists its best themes first. */
export function collectionRank(suite: SuiteId): number {
  return COLLECTIONS[collectionOf(suite)].suites.indexOf(suite);
}
